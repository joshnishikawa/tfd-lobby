export function getLanguage() {
  if (window.tfdI18n && typeof window.tfdI18n.getLanguage === 'function') {
    return window.tfdI18n.getLanguage();
  }
  const stored = localStorage.getItem('site-language') || localStorage.getItem('fly-on-language');
  if (stored && LOCALES[stored]) return stored;
  return 'en';
}

export function setLanguage(lang) {
  if (window.tfdI18n && typeof window.tfdI18n.setLanguage === 'function') {
    window.tfdI18n.setLanguage(lang);
    return;
  }
  if (LOCALES[lang]) {
    localStorage.setItem('site-language', lang);
    localStorage.setItem('fly-on-language', lang);
    document.documentElement.lang = lang;
  }
}

export function t(key, params = {}) {
  if (window.tfdI18n && typeof window.tfdI18n.t === 'function') {
    return window.tfdI18n.t(key, params);
  }
  const lang = getLanguage();
  const keys = key.split('.');
  let val = LOCALES[lang];

  for (const k of keys) {
    if (val && typeof val === 'object' && k in val) {
      val = val[k];
    } else {
      val = null;
      break;
    }
  }

  if (val === null || val === undefined) {
    val = LOCALES['en'];
    for (const k of keys) {
      if (val && typeof val === 'object' && k in val) {
        val = val[k];
      } else {
        return params.defaultValue || key;
      }
    }
  }

  if (typeof val === 'string') {
    return val.replace(/\{\{(\w+)\}\}/g, (match, pName) => {
      return params[pName] !== undefined ? params[pName] : match;
    });
  }

  return val || key;
}

export function translateDOM(container = document) {
  if (window.tfdI18n && typeof window.tfdI18n.translateDOM === 'function') {
    window.tfdI18n.translateDOM(container);
    return;
  }
  const elements = container.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });

  const inputs = container.querySelectorAll('[data-i18n-placeholder]');
  inputs.forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.setAttribute('placeholder', t(key));
  });

  const titles = container.querySelectorAll('[data-i18n-title]');
  titles.forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.setAttribute('title', t(key));
  });
}

